using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Domian.Entities.Common;

namespace Domian.Entities.Gamification
{
    /// <summary>XP, gems, streak and daily counters. One row per learner, created on first use.</summary>
    public class UserStats
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.None)]
        public long UserId { get; set; }

        public int TotalXp { get; set; }
        public int Gems { get; set; }
        public int Streak { get; set; }
        public int LongestStreak { get; set; }

        /// <summary>Last day (learner's local date) with a completed activity.</summary>
        public DateOnly? LastActiveDay { get; set; }

        /// <summary>Activities a day the learner aims for (2-12); null = no goal.</summary>
        public int? DailyGoal { get; set; }

        /// <summary>The day the "today" counters below belong to; they reset when it changes.</summary>
        public DateOnly? CounterDay { get; set; }
        public int ActivitiesToday { get; set; }
        public int XpToday { get; set; }
        public bool PerfectToday { get; set; }

        public DateOnly? InterviewDate { get; set; }

        /// <summary>Equipped cosmetic per slot as JSON: { "title": "title-bit", "theme": "theme-coddify" }.</summary>
        public string EquippedJson { get; set; } = "{}";

        /// <summary>Up to five pinned cosmetic keys as JSON array, in pick order.</summary>
        public string ShowcaseJson { get; set; } = "[]";

        public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;
    }

    /// <summary>One row per learner per day with at least one completed activity (streak calendar).</summary>
    public class ActivityDay
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        public long UserId { get; set; }
        public DateOnly Day { get; set; }
        public int Activities { get; set; }
        public int Xp { get; set; }
    }

    /// <summary>XP earned in one league week (weeks start on Monday). Drives the leaderboard.</summary>
    public class WeeklyXp
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        public long UserId { get; set; }
        public DateOnly WeekStart { get; set; }
        public int Xp { get; set; }
    }

    public class Follow
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        public long FollowerId { get; set; }
        public long FolloweeId { get; set; }
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    }

    /// <summary>A store cosmetic. Unlocked by progress (never bought); admins can add more.</summary>
    public class CosmeticItem : IPublishable
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        /// <summary>Stable public id, e.g. "theme-midnight".</summary>
        [MaxLength(100)]
        public string Key { get; set; } = "";

        /// <summary>themes | tutors | profile</summary>
        [MaxLength(20)]
        public string Tab { get; set; } = "profile";

        /// <summary>title | frame | name-effect | streak-flame | theme | tutor</summary>
        [MaxLength(20)]
        public string Kind { get; set; } = "title";

        [MaxLength(100)]
        public string Name { get; set; } = "";

        [MaxLength(300)]
        public string Description { get; set; } = "";

        /// <summary>Key the frontend uses to draw it (icon, frame style, tutor look…).</summary>
        [MaxLength(50)]
        public string Art { get; set; } = "";

        /// <summary>common | rare | legendary</summary>
        [MaxLength(20)]
        public string Rarity { get; set; } = "common";

        /// <summary>xp | level | streak | lessons | solved; null = unlocked from the start.</summary>
        [MaxLength(20)]
        public string? UnlockMetric { get; set; }

        public int UnlockTarget { get; set; }

        public int Order { get; set; }
        public bool IsPublished { get; set; } = true;
        public bool IsArchived { get; set; }
    }

    /// <summary>Motivational quote of the day. Seeded now; generated by the AI tutor later.</summary>
    public class DailyQuote
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public long Id { get; set; }

        [MaxLength(500)]
        public string Text { get; set; } = "";

        [MaxLength(100)]
        public string Author { get; set; } = "";

        /// <summary>Day this quote is pinned to; null = part of the rotation pool.</summary>
        public DateOnly? Day { get; set; }

        public int Likes { get; set; }
    }
}
